// Release key shared by every build machine (see docs/SETUP.md). The password lives in the
// user-level ~/.gradle/gradle.properties, never in the repo.
val releaseKeystore = file(
    providers.gradleProperty("driveSync.releaseStoreFile").orNull
        ?: (System.getProperty("user.home") + "/.android/drivesync-release.jks")
)
val releaseKeyPassword: String? = providers.gradleProperty("driveSync.releaseKeyPassword").orNull
val hasReleaseKey = releaseKeystore.isFile && releaseKeyPassword != null

android {
    namespace = "com.almodhayan.drivesync"
    compileSdk = 35

    defaultConfig {
        applicationId = "com.kahflabs.wasl"
        minSdk = 30
        targetSdk = 35
        versionCode = 12
        versionName = "0.4.3"
        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
        vectorDrawables { useSupportLibrary = true }
        // libwasl is built for these ABIs only (SRS FR-E1); JNA's others would load without it.
        ndk { abiFilters += listOf("arm64-v8a", "x86_64") }
    }

    signingConfigs {
        // Debug builds use each machine's own ~/.android/debug.keystore (the AGP default),
        // so every machine has its own debug SHA-1 registered as an OAuth client.
        if (hasReleaseKey) {
            create("release") {
                storeFile = releaseKeystore
                storePassword = releaseKeyPassword
                keyAlias = "drivesync"
                keyPassword = releaseKeyPassword
            }
        }
    }

    buildTypes {
        release {
            // R8 (security review S5-1): unused library code and resources leave the APK. The keep
            // rules in proguard-rules.pro hold everything reached by name at run time (JNA, the
            // UniFFI bindings, the app's own classes); see the file for why each one is there.
            isMinifyEnabled = true
            isShrinkResources = true
            signingConfig = signingConfigs.findByName("release")
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
        isCoreLibraryDesugaringEnabled = false
    }

    kotlin {
        compilerOptions {
            jvmTarget.set(JvmTarget.JVM_17)
            freeCompilerArgs.addAll(
                "-opt-in=kotlinx.coroutines.ExperimentalCoroutinesApi",
                "-opt-in=androidx.compose.material3.ExperimentalMaterial3Api",
                "-opt-in=androidx.compose.foundation.ExperimentalFoundationApi",
                "-opt-in=kotlin.ExperimentalStdlibApi",
            )
        }
    }

    androidResources {
        // Per-app language (Android 13+) lists the locales res/values-* provide.
        generateLocaleConfig = true
    }

    buildFeatures {
        compose = true
        buildConfig = true
    }

    packaging {
        resources {
            excludes += setOf(
                "/META-INF/{AL2.0,LGPL2.1}",
                "META-INF/DEPENDENCIES",
                "META-INF/INDEX.LIST",
                "META-INF/versions/9/OSGI-INF/MANIFEST.MF",
            )
        }
    }

    testOptions {
        unitTests.isReturnDefaultValues = true
        // Resources are needed by the Robolectric design gallery (fonts, drawables).
        unitTests.isIncludeAndroidResources = true
        unitTests.all { it.maxHeapSize = "2g" }
    }
}

// Without the shared key AGP would quietly produce app-release-unsigned.apk; fail instead.
// No declared outputs, so this never counts as up to date and runs on every release build.
val checkReleaseSigningKey by tasks.registering {
    val keyFound = hasReleaseKey
    val keystorePath = releaseKeystore.path
    doLast {
        if (!keyFound) throw GradleException(
            "Release signing key missing. Need $keystorePath and driveSync.releaseKeyPassword " +
                "in ~/.gradle/gradle.properties (see docs/SETUP.md, \"Signing keys\")."
        )
    }
}
tasks.matching { it.name == "preReleaseBuild" }.configureEach { dependsOn(checkReleaseSigningKey) }

ksp {
    arg("room.schemaLocation", "$projectDir/schemas")
    arg("room.incremental", "true")
}

// ---------------------------------------------------------------- libwasl (the Rust engine)
// The engine is built from engine/ with cargo-ndk for the device ABIs, and its Kotlin bindings are
// generated by UniFFI from a host build of the same crate. Nothing generated is committed.
val engineDir: File = rootProject.file("engine")
val cargo: String = File(System.getProperty("user.home"), ".cargo/bin/cargo").let { if (it.exists() || File(it.path + ".exe").exists()) it.path else "cargo" }
val ndkVersionPinned = "28.2.13676358"
val rustJniLibs = layout.buildDirectory.dir("rustJniLibs")
val uniffiKotlin = layout.buildDirectory.dir("generated/uniffi/kotlin")
val hostLibName: String = System.getProperty("os.name").lowercase().let {
    when {
        it.contains("win") -> "wasl_mobile.dll"
        it.contains("mac") -> "libwasl_mobile.dylib"
        else -> "libwasl_mobile.so"
    }
}
val hostLib: File = engineDir.resolve("target/release/$hostLibName")

val buildEngineAndroid by tasks.registering(Exec::class) {
    description = "Builds libwasl_mobile.so (the engine) for the device ABIs."
    workingDir = engineDir
    inputs.dir(engineDir.resolve("crates"))
    inputs.file(engineDir.resolve("Cargo.lock"))
    outputs.dir(rustJniLibs)
    // Only this build's libraries: a renamed one must not linger in the APK.
    doFirst { delete(rustJniLibs) }
    val ndk = android.sdkDirectory.resolve("ndk/$ndkVersionPinned")
    environment("ANDROID_NDK_HOME", ndk.path)
    commandLine(
        cargo, "ndk", "-t", "arm64-v8a", "-t", "x86_64", "-P", "30",
        "-o", rustJniLibs.get().asFile.path, "build", "-p", "wasl-ffi", "--release",
    )
}

val buildEngineHost by tasks.registering(Exec::class) {
    description = "Builds libwasl for this computer (binding generation and JVM tests)."
    workingDir = engineDir
    inputs.dir(engineDir.resolve("crates"))
    inputs.file(engineDir.resolve("Cargo.lock"))
    outputs.file(hostLib)
    commandLine(cargo, "build", "-p", "wasl-ffi", "--release")
}

val generateEngineBindings by tasks.registering(Exec::class) {
    description = "Generates the Kotlin bindings of libwasl."
    dependsOn(buildEngineHost)
    workingDir = engineDir
    inputs.file(hostLib)
    outputs.dir(uniffiKotlin)
    doFirst { delete(uniffiKotlin) }
    commandLine(
        cargo, "run", "--release", "-q", "-p", "wasl-ffi", "--features", "bindgen", "--bin", "uniffi-bindgen", "--",
        "generate", "--library", hostLib.path, "--language", "kotlin", "--no-format",
        "--out-dir", uniffiKotlin.get().asFile.path,
    )
}

android.sourceSets["main"].java.srcDir(uniffiKotlin)
android.sourceSets["main"].jniLibs.srcDir(rustJniLibs)
tasks.named("preBuild") { dependsOn(buildEngineAndroid, generateEngineBindings) }
// JVM unit tests load the host build of libwasl.
tasks.withType<Test>().configureEach {
    dependsOn(buildEngineHost)
    systemProperty("jna.library.path", hostLib.parentFile.path)
}

